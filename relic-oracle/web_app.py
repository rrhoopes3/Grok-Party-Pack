INDEX = f"""
<!doctype html>
<html><head><meta charset="utf-8"><title>THE RELIC ORACLE</title>
<style>{LCARS_ORACLE_CSS}</style>
</head><body>
<div style="max-width:920px; margin:0 auto">
<div class="lcars-frame">
  <h1 style="margin:0; color:#ff9900">THE RELIC ORACLE</h1>
  <div style="opacity:0.6">THE COUNCIL SPEAKS • THROUGH THE RELICS</div>
</div>

<div class="lcars-frame">
  <input type="text" id="question" placeholder="What would you ask the relics?" onkeypress="if(event.key==='Enter') consult()">
  <button class="lcars-btn" onclick="consult()">CONSULT THE COUNCIL</button>
  <div class="oracle" id="answer" style="margin-top:16px">The relics are listening...</div>
</div>

<div class="lcars-frame">
  <h3 style="color:#33ccff">RECENT PROPHECIES</h3>
  <div id="log"></div>
</div>

<div style="text-align:center; opacity:0.4; font-size:0.7em">
  All answers are canon. All questions were already answered in the static.
</div>
</div>

<script>
async function consult() {{
  const q = document.getElementById('question').value.trim();
  if (!q) return;
  document.getElementById('answer').textContent = 'The Council deliberates...';
  const r = await fetch('/api/consult', {{
    method: 'POST',
    headers: {{'Content-Type': 'application/json'}},
    body: JSON.stringify({{question: q}})
  }});
  const p = await r.json();
  document.getElementById('answer').textContent = p.text;
  loadLog();
}}

async function loadLog() {{
  const r = await fetch('/api/log');
  const logs = await r.json();
  const el = document.getElementById('log');
  el.innerHTML = logs.map(l => 
    `<div class="prophecy"><strong>Q:</strong> ${{l.question}}<br><strong>A:</strong><br>${{l.text}}</div>`
  ).join('');
}}

window.onload = loadLog;
</script>
</body></html>
"""

@app.route("/")
def index():
    return render_template_string(INDEX)

@app.route("/api/consult", methods=["POST"])
def api_consult():
    data = request.json or {}
    question = data.get("question", "the meaning of all this suffering")
    prophecy = generate_prophecy(question)
    save_prophecy(prophecy)
    return jsonify(prophecy)

@app.route("/api/log")
def api_log():
    return jsonify(load_recent_prophecies())

